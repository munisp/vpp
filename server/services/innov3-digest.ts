/**
 * Start of the current ISO week (Monday 00:00 UTC). The digested week is
 * [isoWeekStart(now) - 7d, isoWeekStart(now)).
 */
export function isoWeekStart(now: Date): Date {
  const midnightUtc = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const day = (now.getUTCDay() + 6) % 7; // Monday = 0
  return new Date(midnightUtc - day * 86400000);
}

export interface WeeklyRunSummary {
  periodStart: string;
  periodEnd: string;
  enabledSubscriptions: number;
  alreadyProcessed: number;
  sent: number;
  failed: number;
  skipped: number;
}

/**
 * Compile and dispatch the weekly digest to every enabled subscriber.
 * Idempotent per week: a recipient with a digest_runs row for this week's
 * periodStart (any status) is not re-sent.
 */
export async function runWeeklyDigests(now: Date = new Date()): Promise<WeeklyRunSummary> {
  const db = await requireDb();

  const periodEnd = isoWeekStart(now);
  const periodStart = new Date(periodEnd.getTime() - 7 * 86400000);

  const subs = await db.select().from(digestSubscriptions).where(eq(digestSubscriptions.enabled, true));

  const summary: WeeklyRunSummary = {
    periodStart: periodStart.toISOString(),
    periodEnd: periodEnd.toISOString(),
    enabledSubscriptions: subs.length,
    alreadyProcessed: 0,
    sent: 0,
    failed: 0,
    skipped: 0,
  };

  for (const sub of subs) {
    const [existing] = await db
      .select({ id: digestRuns.id })
      .from(digestRuns)
      .where(and(eq(digestRuns.subscriptionId, sub.id), eq(digestRuns.periodStart, periodStart)))
      .limit(1);
    if (existing) {
      summary.alreadyProcessed++;
      continue;
    }

    const stats = await compileWeeklyStats(sub.userId, periodStart, periodEnd);
    const text = renderDigestText(stats);

    let status: 'sent' | 'failed' | 'skipped';
    let error: string | null = null;

    const [user] = await db.select({ email: users.email, phone: users.phone }).from(users).where(eq(users.id, sub.userId)).limit(1);

    if (sub.channel === 'email') {
      if (!user?.email) {
        status = 'skipped';
        error = 'no email address on file';
      } else {
        const result = await sendEmail({
          to: user.email,
          subject: `Your VPP weekly digest (${stats.periodStart.slice(0, 10)} – ${stats.periodEnd.slice(0, 10)})`,
          html: renderDigestHtml(stats),
          text,
        });
        status = result.success ? 'sent' : 'failed';
        error = result.success ? null : result.error ?? 'email service returned failure';
      }
    } else {
      if (!user?.phone) {
        status = 'skipped';
        error = 'no phone number on file';
      } else if (!process.env.AT_API_KEY || !process.env.AT_USERNAME) {
        // Mirror of notifications.sendSMS's own configuration gate, so the
        // run row records the real reason instead of a bare false.
        status = 'failed';
        error = "SMS gateway not configured (AT_API_KEY/AT_USERNAME missing)";
      } else {
        const ok = await sendSMS({ to: user.phone, message: text });
        status = ok ? 'sent' : 'failed';
        error = ok ? null : 'SMS delivery refused by gateway';
      }
    }

    await db.insert(digestRuns).values({
      subscriptionId: sub.id,
      userId: sub.userId,
      channel: sub.channel,
      periodStart,
      periodEnd,
      stats: stats as unknown as Record<string, unknown>,
      status,
      error,
      sentAt: status === 'sent' ? new Date() : null,
    });

    summary[status]++;
  }

  return summary;
}
