/**
 * Weekly Digest Engine (innovation 15)
 *
 * Users opt in per channel (email / SMS). `runWeeklyDigests()` — wired to a
 * weekly cron by the platform scheduler — compiles each subscriber's real
 * stats for the ISO week that just ended (consumption from meter telemetry,
 * generation from solar telemetry, completed payments, vended tokens) and
 * dispatches them through the real channel services
 * (server/_core/emailService.ts SMTP, server/_core/notifications.ts SMS via
 * Africa's Talking).
 *
 * Every dispatch attempt is recorded as a digest_runs row with the exact
 * stats that were compiled and the real outcome:
 *  - `sent`    — the channel service confirmed acceptance,
 *  - `failed`  — the channel service refused or errored; `error` says why,
 *  - `skipped` — not attempted (e.g. no email address on file); `error`
 *    says why.
 * A failed run is never rewritten to sent; a later retry is a new run for a
 * new week (the (subscriptionId, periodStart) unique key makes reruns of
 * the same week idempotent no-ops).
 *
 * Stats are null where the underlying data does not exist, and the message
 * says "no data" for those sections — a week without telemetry is reported
 * as unknown, never as a fabricated zero.
 */

import { and, desc, eq, gte, lt, sql } from 'drizzle-orm';
import { getDb } from '../db';
import { assets, payments, telemetry, tokens, users } from '../../drizzle/schema';
import {
  digestRuns,
  digestSubscriptions,
  type DigestRun,
  type DigestSubscription,
} from '../../drizzle/innov3-market-schema';
import { sendEmail } from '../_core/emailService';
import { sendSMS } from '../_core/notifications';
import { getConsumptionWh } from './innov3-challenges';

async function requireDb() {
  const db = await getDb();
  if (!db) throw new Error('Database not available');
  return db;
}

// ---------------------------------------------------------------------------
// Subscriptions
